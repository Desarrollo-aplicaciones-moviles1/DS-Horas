-- ============================================================
--  DS Horas · Base de datos en Supabase (PostgreSQL)
--  Ejecutar en: Supabase -> SQL Editor -> New query -> pegar -> Run
--  Crea las tablas que usan los microservicios ms-usuarios y ms-horas.
--  Los datos de ejemplo los cargan los microservicios la primera vez que arrancan.
-- ============================================================

-- ---------- ms-usuarios ----------
create table if not exists public.usuarios (
    id             bigint generated by default as identity primary key,
    nombre         varchar(60)  not null,
    email          varchar(120) not null unique,
    password_hash  varchar(255) not null          -- BCrypt, nunca la clave en texto
);

-- ---------- ms-horas ----------
create table if not exists public.proyectos (
    id            bigint generated by default as identity primary key,
    nombre        varchar(40)      not null unique,
    cliente       varchar(40)      not null,
    progreso      double precision not null default 0 check (progreso between 0 and 1),
    fijado        boolean          not null default false,
    fecha_cierre  date                                  -- null = proyecto en curso
);

create table if not exists public.registros (
    id              bigint generated by default as identity primary key,
    proyecto_id     bigint       not null references public.proyectos(id) on delete cascade,
    tarea           varchar(60)  not null,
    fecha           date         not null,
    minutos         integer      not null check (minutos between 1 and 1440),
    foto            varchar(300),
    creado_en       bigint       not null,
    usuario_id      bigint,                              -- quién registró (id en usuarios)
    usuario_nombre  varchar(60)
);

-- Índices para las consultas que más se usan (lista por fecha, tope del día y aporte del equipo)
create index if not exists idx_registros_fecha on public.registros (fecha desc, creado_en desc);
create index if not exists idx_registros_proyecto_usuario on public.registros (proyecto_id, usuario_id);

-- ---------- Seguridad ----------
-- Supabase expone las tablas del esquema public por su API REST automática.
-- Activamos RLS sin políticas: así NADIE puede leerlas desde esa API pública con la clave anon;
-- solo nuestros microservicios, que se conectan con el usuario de la base, pueden usarlas.
alter table public.usuarios  enable row level security;
alter table public.proyectos enable row level security;
alter table public.registros enable row level security;

-- ---------- Vista útil para revisar en el Table Editor ----------
-- Horas y porcentaje de cada integrante por proyecto (lo mismo que muestra la app)
create or replace view public.aporte_equipo
with (security_invoker = true) as
select p.nombre                                       as proyecto,
       coalesce(r.usuario_nombre, 'Sin asignar')      as integrante,
       sum(r.minutos)                                 as minutos,
       round(100.0 * sum(r.minutos) / sum(sum(r.minutos)) over (partition by p.id)) as porcentaje
from public.registros r
join public.proyectos p on p.id = r.proyecto_id
group by p.id, p.nombre, r.usuario_nombre
order by p.nombre, minutos desc;
